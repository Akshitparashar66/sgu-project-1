"""Flood thresholds for the Hindon flow forecast, from GloFAS's own history.

    python data/build_glofas_thresholds.py

GloFAS (Copernicus Global Flood Awareness System, served free by Open-Meteo)
models river discharge on a ~5 km grid. The cell at 28.675 N, 77.375 E is the
Hindon's main channel beside Raj Nagar Extension: on 2026-10-24 the cells along
77.325-77.375 E carried 12-16 m3/s, growing downstream, while their neighbours
carried under 1.

Thresholds follow GloFAS's own practice: the 2-, 5- and 20-year return-period
flows, fitted here with a Gumbel distribution (method of moments) to this
cell's annual maxima over every complete year of reanalysis. The result is
written to data/hindon_glofas.json, which the app reads; it never changes the
district's gauge thresholds.
"""
from __future__ import annotations

import json
import math
import statistics
import urllib.request
from datetime import date
from pathlib import Path

LAT, LON = 28.675, 77.375
FIRST_YEAR, LAST_YEAR = 1984, 2025  # the API has data from 1997 for this cell
OUT = Path(__file__).resolve().parent / "hindon_glofas.json"
RETURN_PERIODS = {"warning": 2, "severe": 5, "extreme": 20}


def main() -> None:
    url = (f"https://flood-api.open-meteo.com/v1/flood?latitude={LAT}&longitude={LON}&daily=river_discharge"
           f"&start_date={FIRST_YEAR}-01-01&end_date={LAST_YEAR}-12-31")
    with urllib.request.urlopen(url, timeout=120) as response:
        data = json.load(response)
    days, flows = data["daily"]["time"], data["daily"]["river_discharge"]

    peak: dict[str, float] = {}
    count: dict[str, int] = {}
    for day, flow in zip(days, flows):
        if flow is not None:
            year = day[:4]
            peak[year] = max(peak.get(year, 0.0), flow)
            count[year] = count.get(year, 0) + 1
    complete = sorted(y for y in peak if count[y] >= 360)
    maxima = [peak[y] for y in complete]

    mean, sd = statistics.mean(maxima), statistics.stdev(maxima)
    beta = sd * math.sqrt(6) / math.pi
    mu = mean - 0.5772 * beta

    def flow_for(years: int) -> float:
        return round(mu - beta * math.log(-math.log(1 - 1 / years)))

    result = {
        "note": "Generated by data/build_glofas_thresholds.py. A model forecast for a ~5 km cell, not a gauge.",
        "river": "Hindon",
        "cell": {"latitude": data["latitude"], "longitude": data["longitude"]},
        "source": "GloFAS via Open-Meteo Flood API (flood-api.open-meteo.com)",
        "method": "Gumbel fit (method of moments) to annual maximum daily discharge; GloFAS-style return periods",
        "years": f"{complete[0]}-{complete[-1]}",
        "yearCount": len(complete),
        "thresholdsM3s": {level: flow_for(years) for level, years in RETURN_PERIODS.items()},
        "returnPeriodYears": RETURN_PERIODS,
        "largestYears": {y: round(peak[y]) for y in sorted(complete, key=lambda y: -peak[y])[:5]},
        "knownMiss": ("July 2023: the Hindon flooded parts of Noida and Ghaziabad, but this cell's 2023 peak was "
                      f"{round(peak.get('2023', 0))} m3/s, below the 2-year flow; most likely local rain and Yamuna backwater, which "
                      "a 5 km river model does not capture."),
        "computedOn": date.today().isoformat(),
    }
    OUT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result["thresholdsM3s"]), f"from {len(complete)} years ({result['years']})")


if __name__ == "__main__":
    main()
