/** The orders as a sheet a coordinator can print and read out, in English or Hindi. */
export function OrderSheet({ orders, interventions, scenario, clearanceMinutes, language, prepared }: {
  orders: EvacuationOrder[];
  interventions?: PlanInterventions;
  scenario: ScenarioConfig;
  clearanceMinutes: number | null;
  language: Language;
  prepared: string;
}) {
  const t = TEXT[language];
  const zoneName = (id: string) => scenario.zones.find((z) => z.id === id)?.name ?? id;
  const shelterName = (id: string) => scenario.shelters.find((s) => s.id === id)?.name ?? id;
  const waves = [...new Set(orders.map((o) => o.departureMinute))].sort((a, b) => a - b);
  const total = orders.reduce((n, o) => n + o.people, 0);

  return (
    <article lang={language} className="print-sheet mx-auto max-w-3xl bg-white p-8 text-slate-900">
      <header className="border-b-2 border-slate-900 pb-3">
        <h1 className="text-2xl font-bold">{t.title}</h1>
        <p className="mt-1 text-sm">
          {t.scenario}: <strong>{scenario.name}</strong> · {t.prepared}: {prepared} · {t.total(total)}
        </p>
        {clearanceMinutes !== null && <p className="mt-1 text-sm">{t.clearance(clearanceMinutes)}</p>}
      </header>

      {interventions && (interventions.openedShelters.length > 0 || interventions.marshalledRoads.length > 0) && (
        <ul className="mt-4 list-disc pl-6 text-sm">
          {interventions.openedShelters.map((s) => <li key={s.shelterId}>{t.openShelter}: <strong>{s.name}</strong></li>)}
          {interventions.marshalledRoads.map((r) => <li key={r}>{t.marshals}: <strong>{r}</strong></li>)}
        </ul>
      )}

      {waves.map((minute) => (
        <section key={minute} className="mt-5 break-inside-avoid">
          <h2 className="border-b border-slate-400 pb-1 text-lg font-bold">
            {t.leaveAt}: {minute === 0 ? t.now : t.minutes(minute)}
          </h2>
          <table className="mt-2 w-full border-collapse text-sm">
            <thead>
              <tr className="text-left">
                <th className="border border-slate-400 px-2 py-1">{t.from}</th>
                <th className="border border-slate-400 px-2 py-1 text-right">{t.people}</th>
                <th className="border border-slate-400 px-2 py-1">{t.toShelter}</th>
                <th className="border border-slate-400 px-2 py-1">{t.route}</th>
              </tr>
            </thead>
            <tbody>
              {orders.filter((o) => o.departureMinute === minute).map((o) => (
                <tr key={`${o.zoneId}-${o.movementProfile}-${o.shelterId}-${o.routeEdgeIds.join()}`}>
                  <td className="border border-slate-400 px-2 py-1">
                    {zoneName(o.zoneId)}{o.movementProfile !== "standard" && ` (${t.slow})`}
                  </td>
                  <td className="border border-slate-400 px-2 py-1 text-right tabular-nums">{o.people}</td>
                  <td className="border border-slate-400 px-2 py-1">{shelterName(o.shelterId)}</td>
                  <td className="border border-slate-400 px-2 py-1">{o.routeEdgeIds.join(" → ")}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}

      <p className="mt-10 border-t border-slate-900 pt-2 text-sm">{t.signature}</p>
      <p className="mt-6 text-xs text-slate-600">{t.disclaimer}</p>
    </article>
  );
}

/** Full-screen preview with a language switch; the browser's print dialog prints only the sheet. */
export function PrintOrdersDialog(props: Omit<Parameters<typeof OrderSheet>[0], "language" | "prepared"> & { onClose: () => void }) {
  const [language, setLanguage] = useState<Language>("en");
  const { onClose, ...sheet } = props;
  const t = TEXT[language];
  const prepared = new Date().toLocaleString(language === "hi" ? "hi-IN" : "en-IN", { dateStyle: "medium", timeStyle: "short" });
  return (
    <div role="dialog" aria-modal="true" aria-label={t.title} className="print-root fixed inset-0 z-[2000] overflow-y-auto bg-slate-100">
      <div className="no-print sticky top-0 flex items-center justify-end gap-2 border-b border-slate-200 bg-white px-4 py-2">
        <div role="group" aria-label="Language" className="flex rounded-md border border-slate-200 text-sm">
          {([["en", "English"], ["hi", "हिन्दी"]] as const).map(([code, label]) => (
            <button
              key={code}
              type="button"
              aria-pressed={language === code}
              onClick={() => setLanguage(code)}
              className={`px-3 py-1.5 ${language === code ? "bg-blue-600 text-white" : "text-slate-700 hover:bg-slate-100"}`}
            >
              {label}
            </button>
          ))}
        </div>
        <button type="button" onClick={() => window.print()} className="inline-flex items-center gap-1.5 rounded-md bg-blue-600 px-3 py-1.5 text-sm font-semibold text-white hover:bg-blue-700">
          <Printer size={15} aria-hidden /> {t.print}
        </button>
        <button type="button" onClick={onClose} className="inline-flex items-center gap-1.5 rounded-md border border-slate-200 px-3 py-1.5 text-sm text-slate-700 hover:bg-slate-100">
          <X size={15} aria-hidden /> {t.close}
        </button>
      </div>
      <div className="py-6">
        <OrderSheet {...sheet} language={language} prepared={prepared} />
      </div>
    </div>
  );
}
